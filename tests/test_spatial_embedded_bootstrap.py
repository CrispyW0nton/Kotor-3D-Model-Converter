def test_windows_moniker_derivation_matches_mcpstudio_base64url_contract() -> None:
    module = _auth_module()
    approval_id = "0123456789abcdef" * 4
    encoded = base64.urlsafe_b64encode(
        bytes.fromhex(approval_id)
    ).decode("ascii").rstrip("=")

    moniker = module.derive_windows_spatial_profile_moniker(approval_id)

    assert moniker == f"GhostMCPStudio.{encoded}"
    assert len(encoded) == 43


def test_windows_profile_bootstrap_requires_fixed_packages_root_and_low_il(
    tmp_path: Path,
) -> None:
    module = _auth_module()
    anchor = _anchor(module)
    local_app_data = tmp_path / "Local"
    moniker = module.derive_windows_spatial_profile_moniker(
        anchor.approval_id
    )
    packages_root = local_app_data / "Packages"
    profile_root = packages_root / moniker / "AC"
    profile_root.mkdir(parents=True)
    audited: list[Path] = []

    bootstrap = module.resolve_windows_spatial_server_bootstrap(
        anchor,
        environ={"LOCALAPPDATA": str(local_app_data)},
        native_profile_resolver=lambda observed: (
            PACKAGE_SID,
            profile_root,
        )
        if observed == moniker
        else pytest.fail("unexpected moniker"),
        low_integrity_audit=audited.append,
    )

    assert bootstrap.anchor == anchor
    assert bootstrap.identity.moniker == moniker
    assert bootstrap.identity.package_sid == PACKAGE_SID
    assert bootstrap.identity.profile_root == profile_root
    assert bootstrap.session_path == (
        profile_root
        / "MCPStudioState"
        / "GhostStudioSpatial"
        / "ghoststudio-session.json"
    )
    assert audited == [profile_root]


def test_windows_profile_bootstrap_rejects_wrong_root_and_placeholder(
    tmp_path: Path,
) -> None:
    module = _auth_module()
    local_app_data = tmp_path / "Local"
    wrong_root = tmp_path / "Other" / "profile"
    wrong_root.mkdir(parents=True)

    with pytest.raises(module.SpatialAuthenticationError) as placeholder:
        module.resolve_windows_spatial_server_bootstrap(
            _anchor(module, "0" * 64),
            environ={"LOCALAPPDATA": str(local_app_data)},
            native_profile_resolver=lambda _moniker: (
                PACKAGE_SID,
                wrong_root,
            ),
            low_integrity_audit=lambda _path: None,
        )
    assert placeholder.value.code == "unapproved-spatial-profile"

    with pytest.raises(module.SpatialAuthenticationError) as wrong:
        module.resolve_windows_spatial_server_bootstrap(
            _anchor(module),
            environ={"LOCALAPPDATA": str(local_app_data)},
            native_profile_resolver=lambda _moniker: (
                PACKAGE_SID,
                wrong_root,
            ),
            low_integrity_audit=lambda _path: None,
        )
    assert wrong.value.code == "invalid-spatial-profile-root"


