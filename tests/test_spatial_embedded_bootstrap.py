def _auth_module():
    spec = importlib.util.spec_from_file_location(
        "ghoststudio_spatial_embedded_bootstrap_test_module",
        AUTH_MODULE,
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _anchor(module, approval_id: str = "ab" * 32):
    return module.SpatialProfileAnchor(
        schema="ghoststudio-spatial-profile-anchor/v1",
        adapter_id="ghoststudio",
        approval_id=approval_id,
        transport="windows-named-pipe-v1",
        identity_derivation="approval-sha256-base64url-userenv-v1",
    )


def _qt_start_ipc_server_method(namespace: dict[str, object]):
    tree = ast.parse(QT_MAIN_WINDOW.read_text(encoding="utf-8"))
    window_class = next(
        node
        for node in tree.body
        if isinstance(node, ast.ClassDef)
        and node.name == "QtGhostRiggerMainWindow"
    )
    method = next(
        node
        for node in window_class.body
        if isinstance(node, ast.FunctionDef)
        and node.name == "_start_ipc_server"
    )
    module = ast.fix_missing_locations(
        ast.Module(body=[method], type_ignores=[])
    )
    exec(compile(module, str(QT_MAIN_WINDOW), "exec"), namespace)
    return namespace["_start_ipc_server"]


class _FakeWindow:
    def __init__(self) -> None:
        self._ipc_server = None
        self._scripter_compat_ipc_server = None
        self.messages: list[tuple[str, str]] = []

    def _log(self, message: str, level: str) -> None:
        self.messages.append((message, level))

    def __getattr__(self, _name: str):
        return lambda *_args, **_kwargs: {}


class _FakeIPCServer:
    instances: list["_FakeIPCServer"] = []
    fail_start_indexes: set[int] = set()

    def __init__(self, callbacks, **kwargs) -> None:
        self.callbacks = callbacks
        self.kwargs = kwargs
        self.index = len(self.instances)
        self.port = int(kwargs.get("port", 7001))
        self.start_calls = 0
        self.stop_calls = 0
        self.instances.append(self)

    def start(self) -> None:
        self.start_calls += 1
        if self.index in self.fail_start_indexes:
            raise RuntimeError("expected startup failure")

    def stop(self) -> None:
        self.stop_calls += 1


def _qt_start_namespace(spatial_bootstrap):
    _FakeIPCServer.instances = []
    _FakeIPCServer.fail_start_indexes = set()
    return {
        "GhostRiggerIPCServer": _FakeIPCServer,
        "_resolve_optional_spatial_bootstrap": lambda: spatial_bootstrap,
        "os": SimpleNamespace(
            environ={"GHOSTSTUDIO_SCRIPTER_IPC_PORT": "7002"}
        ),
        "log": SimpleNamespace(exception=lambda *_args, **_kwargs: None),
    }


def test_embedded_anchor_has_the_exact_generated_byte_contract() -> None:
    anchor = _auth_module().load_embedded_spatial_profile_anchor()
    assert re.fullmatch(r"[a-f0-9]{64}", anchor.approval_id)
    assert anchor.approval_id != "0" * 64
    expected = (
        '# Generated by MCPStudio; do not edit.\n'
        'SCHEMA = "ghoststudio-spatial-profile-anchor/v1"\n'
        'ADAPTER_ID = "ghoststudio"\n'
        f'APPROVAL_ID = "{anchor.approval_id}"\n'
        'TRANSPORT = "windows-named-pipe-v1"\n'
        'IDENTITY_DERIVATION = '
        '"approval-sha256-base64url-userenv-v1"\n'
    ).encode("utf-8")

    assert ANCHOR_MODULE.read_bytes() == expected


def test_embedded_anchor_loader_wraps_parse_failures_with_stable_code(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    module = _auth_module()

    class _FailingLoader:
        def exec_module(self, _module) -> None:
            raise SyntaxError("private parser detail")

    spec = SimpleNamespace(loader=_FailingLoader())
    monkeypatch.setattr(
        module.importlib.util,
        "spec_from_file_location",
        lambda *_args, **_kwargs: spec,
    )
    monkeypatch.setattr(
        module.importlib.util,
        "module_from_spec",
        lambda _spec: SimpleNamespace(),
    )

    with pytest.raises(module.SpatialAuthenticationError) as error:
        module.load_embedded_spatial_profile_anchor()

    assert error.value.code == "invalid-spatial-profile-anchor"


