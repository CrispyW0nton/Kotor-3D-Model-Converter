def test_gui_spatial_startup_fails_closed_without_tearing_down_legacy_ipc(
) -> None:
    bootstrap = object()
    namespace = _qt_start_namespace(bootstrap)
    _FakeIPCServer.fail_start_indexes = {0}
    start_ipc_server = _qt_start_ipc_server_method(namespace)
    window = _FakeWindow()

    start_ipc_server(window)

    spatial_attempt, legacy_fallback, compatibility = (
        _FakeIPCServer.instances
    )
    assert spatial_attempt.kwargs["spatial_bootstrap"] is bootstrap
    assert spatial_attempt.stop_calls == 1
    assert legacy_fallback.kwargs["spatial_bootstrap"] is None
    assert "spatial_session_path" not in legacy_fallback.kwargs
    assert legacy_fallback.stop_calls == 0
    assert compatibility.kwargs["program_name"] == (
        "GhostStudio Scripting Suite"
    )
    assert compatibility.stop_calls == 0
    assert window._ipc_server is legacy_fallback
    assert window._scripter_compat_ipc_server is compatibility


def test_gui_ipc_startup_retries_only_the_missing_independent_server() -> None:
    namespace = _qt_start_namespace(None)
    start_ipc_server = _qt_start_ipc_server_method(namespace)
    window = _FakeWindow()
    existing_primary = SimpleNamespace(port=7001, stop_calls=0)
    window._ipc_server = existing_primary

    start_ipc_server(window)

    assert window._ipc_server is existing_primary
    assert len(_FakeIPCServer.instances) == 1
    assert _FakeIPCServer.instances[0].kwargs["program_name"] == (
        "GhostStudio Scripting Suite"
    )
    assert window._scripter_compat_ipc_server is _FakeIPCServer.instances[0]


def test_gui_compatibility_failure_never_stops_primary_server() -> None:
    namespace = _qt_start_namespace(None)
    _FakeIPCServer.fail_start_indexes = {1}
    start_ipc_server = _qt_start_ipc_server_method(namespace)
    window = _FakeWindow()

    start_ipc_server(window)

    primary, compatibility = _FakeIPCServer.instances
    assert window._ipc_server is primary
    assert primary.stop_calls == 0
    assert compatibility.stop_calls == 1
    assert window._scripter_compat_ipc_server is None
